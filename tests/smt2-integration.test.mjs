import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const html=fs.readFileSync('index.html','utf8');
const code=fs.readFileSync('smt2.js','utf8');
const config=fs.readFileSync('smt2-config.example.js','utf8');
test('SMT2 is embedded',()=>assert.ok(html.includes('id="smt2-content"')));
test('SMT2 loads direct Sheets API',()=>assert.ok(code.includes('sheets.googleapis.com')));
test('SMT2 has no Apps Script shortcut',()=>assert.ok(!html.includes('script.google.com/macros')));
test('SMT2 menu is hidden by default',()=>assert.match(html,/data-smt2-menu[^>]*hidden|hidden[^>]*data-smt2-menu/));
test('SMT2 requires OAuth before private request',()=>assert.match(code,/if \(!token\) return;/));
test('SMT2 does not persist OAuth token in local storage',()=>assert.doesNotMatch(code,/localStorage\.|sessionStorage\.|indexedDB\./));
test('SMT2 uses readonly Sheets scope',()=>assert.ok(code.includes('auth/spreadsheets.readonly')));
test('SMT2 config includes client ID',()=>assert.ok(config.includes('105328800542-37q8v4ae1tp6p314gki4gi2icdlg40np.apps.googleusercontent.com')));
test('SMT2 displays errors after failed access',()=>assert.ok(code.includes("showContent('smt2'); message(reason)")));
